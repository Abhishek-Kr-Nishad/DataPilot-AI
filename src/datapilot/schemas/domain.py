"""Pydantic domain schemas for pipeline runs, quality reports, and agent diagnostics."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Literal

from pydantic import BaseModel, Field

ExecutionMode = Literal["local", "aws"]
PipelineStatus = Literal["PENDING", "RUNNING", "SUCCESS", "QUALITY_FAILED", "FAILED"]
CheckSeverity = Literal["ERROR", "WARNING", "INFO"]
ApprovalStatus = Literal["PENDING_APPROVAL", "APPROVED", "REJECTED"]
RiskLevel = Literal["LOW", "MEDIUM", "HIGH"]


def utc_now_iso() -> str:
    """Return an ISO-8601 UTC timestamp string."""
    return datetime.now(timezone.utc).isoformat()


class LayerMetrics(BaseModel):
    """Metrics describing a materialized Medallion layer output."""

    layer: str
    path: str
    format: str = "parquet"
    row_count: int = 0
    column_count: int = 0
    columns: list[str] = Field(default_factory=list)
    execution_mode: ExecutionMode = "local"
    s3_uri: str | None = None


class QualityCheckResult(BaseModel):
    """Single deterministic data quality assertion outcome."""

    check_name: str
    passed: bool
    severity: CheckSeverity = "ERROR"
    metric_value: float | int | str
    threshold: str
    affected_rows: int = 0
    details: str


class QualityReport(BaseModel):
    """Full data quality evaluation report for a pipeline run."""

    run_id: str
    dataset_name: str
    generated_at: str = Field(default_factory=utc_now_iso)
    execution_mode: ExecutionMode = "local"
    overall_passed: bool
    quality_score: float = Field(default=100.0, ge=0.0, le=100.0)
    total_bronze_rows: int
    valid_silver_rows: int
    quarantined_rows: int
    duplicate_rows_removed: int
    schema_valid: bool
    missing_columns: list[str] = Field(default_factory=list)
    unexpected_columns: list[str] = Field(default_factory=list)
    null_counts: dict[str, int] = Field(default_factory=dict)
    null_rates: dict[str, float] = Field(default_factory=dict)
    quarantine_reason_counts: dict[str, int] = Field(default_factory=dict)
    checks: list[QualityCheckResult] = Field(default_factory=list)
    summary: str


def compute_quality_score(
    total_bronze_rows: int,
    valid_silver_rows: int,
    checks: list[QualityCheckResult],
    schema_valid: bool,
) -> float:
    """Compute a deterministic 0-100 data quality score from check pass rate and valid yield."""
    if not schema_valid:
        return 0.0
    if total_bronze_rows <= 0:
        return 0.0
    passed_checks = sum(1 for c in checks if c.passed)
    check_ratio = passed_checks / len(checks) if checks else 1.0
    valid_ratio = min(1.0, max(0.0, valid_silver_rows / total_bronze_rows))
    return round((check_ratio * 0.6 + valid_ratio * 0.4) * 100.0, 2)


class PipelineRunRecord(BaseModel):
    """Persistent manifest tracking an individual pipeline execution."""

    run_id: str
    batch_id: str
    started_at: str = Field(default_factory=utc_now_iso)
    completed_at: str | None = None
    status: PipelineStatus = "PENDING"
    requested_mode: ExecutionMode = "local"
    effective_mode: ExecutionMode = "local"
    aws_synced: bool = False
    fallback_reason: str | None = None
    source_file: str
    scenario: str = "clean"
    layers: dict[str, LayerMetrics] = Field(default_factory=dict)
    quality_report_path: str | None = None
    error_type: str | None = None
    error_message: str | None = None
    duration_seconds: float | None = None
    notes: list[str] = Field(default_factory=list)


class FailureDiagnosis(BaseModel):
    """Structured root-cause diagnosis generated by the diagnostic agent."""

    run_id: str
    diagnosed_at: str = Field(default_factory=utc_now_iso)
    status_observed: str
    failure_category: str
    severity: Literal["LOW", "MEDIUM", "HIGH", "CRITICAL"]
    root_cause: str
    evidence: list[str] = Field(default_factory=list)
    affected_layers: list[str] = Field(default_factory=list)
    confidence: float = Field(ge=0.0, le=1.0)


class SQLValidationPack(BaseModel):
    """Read-only Amazon Athena validation queries for pipeline verification."""

    run_id: str
    database_name: str
    dialect: str = "athena"
    queries: dict[str, str] = Field(default_factory=dict)
    read_only_verified: bool = True


class RecoveryAction(BaseModel):
    """Proposed human-reviewed remediation step (never auto-executed)."""

    action_id: str
    title: str
    description: str
    command_or_step: str
    risk_level: RiskLevel = "MEDIUM"
    destructive: bool = False
    rollback_plan: str


class RecoveryRecommendation(BaseModel):
    """Complete recovery proposal awaiting explicit human approval."""

    recommendation_id: str
    run_id: str
    created_at: str = Field(default_factory=utc_now_iso)
    diagnosis_summary: str
    failure_category: str
    actions: list[RecoveryAction] = Field(default_factory=list)
    requires_human_approval: bool = True
    approval_status: ApprovalStatus = "PENDING_APPROVAL"
    approved_by: str | None = None
    approved_at: str | None = None
    reviewer_notes: str | None = None
    auto_executed: bool = False


class ApprovalDecision(BaseModel):
    """Audit event recording a human reviewer decision on a recommendation."""

    recommendation_id: str
    run_id: str
    decision: Literal["APPROVED", "REJECTED"]
    reviewer: str
    notes: str = ""
    decided_at: str = Field(default_factory=utc_now_iso)


class AgentDiagnosisReport(BaseModel):
    """End-to-end structured output produced by DiagnosticAgent."""

    run_id: str
    generated_at: str = Field(default_factory=utc_now_iso)
    execution_mode: ExecutionMode = "local"
    llm_provider: Literal["mock", "gemini"] = "mock"
    llm_model: str | None = None
    pipeline_status: str
    quality_summary: str
    diagnosis: FailureDiagnosis
    sql_validation: SQLValidationPack
    recommendation: RecoveryRecommendation
    llm_enhanced: bool = False
    narrative_summary: str
    tool_trace: list[dict[str, str]] = Field(default_factory=list)
